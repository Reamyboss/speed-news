import type { LicenseMode, SourceStatus, SourceType } from "../lib/taxonomy";

/**
 * THE SOURCE REGISTRY (seed data).
 *
 * Every story on the platform traces back to exactly one entry here. Sources
 * are explicitly NOT equal: `type` and `trustTier` decide how prominently an
 * item can appear and how it is labelled for the reader.
 *
 * `status` starts as declared below; `scripts/probe-sources.ts` verifies each
 * feed against the live web and demotes anything that does not respond to
 * BROKEN, so the registry stays honest rather than aspirational.
 *
 * Licensing posture: we ingest feed metadata (headline, standfirst, link,
 * image, timestamp) and publish an original summary plus attribution and a
 * link out. We never mirror a full article body.
 */
